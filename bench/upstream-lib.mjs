// The pure half of the upstream comparison: how an answer is judged, how the judgements are
// counted, and how the result is written. No file, process or network access, so
// test/compare-upstream.test.mjs can run it on invented answers.

const MINUTE_MS = 60_000;

/** "2026-03-08T07:00:00.000Z" as "2026-03-08 07:00Z", the form the tables use. */
export const short = (iso) => iso.replace("T", " ").replace(/:00\.000Z$/, "Z").replace(/\.000Z$/, "Z");

/**
 * Judges one tool's answer to "is this instant inside quiet hours?".
 * `answer` is { quiet } or undefined when the tool cannot be asked.
 */
export function judgeQuiet(answer, truth) {
  if (!answer) return { text: "not available", ok: null };
  return answer.quiet === truth.quiet ? { text: answer.quiet ? "quiet" : "open", ok: true } : { text: `${answer.quiet ? "quiet" : "open"} (wrong)`, ok: false };
}

/**
 * Judges one tool's answer to "when may the message go?" for a case that is inside quiet hours.
 * `answer` is { quiet, next } with next an ISO instant or null, or undefined when the tool cannot be asked.
 * A tool that says the instant is open has answered the first question wrongly, so the second is wrong too.
 */
export function judgeNext(answer, truth) {
  if (!answer) return { text: "not available", ok: null };
  if (!answer.quiet) return { text: "says open (wrong)", ok: false };
  if (!answer.next) return { text: "no answer", ok: false };
  const minutes = Math.round((Date.parse(answer.next) - Date.parse(truth.next)) / MINUTE_MS);
  if (minutes === 0) return { text: short(answer.next), ok: true };
  const sign = minutes > 0 ? "+" : "-";
  const hours = Math.abs(minutes) % 60 === 0 && Math.abs(minutes) >= 60 ? `${Math.abs(minutes) / 60} h` : `${Math.abs(minutes)} min`;
  return { text: `${short(answer.next)} (${sign}${hours}${minutes > 0 ? ", later than needed" : ", inside quiet hours"})`, ok: false };
}

/**
 * Judges one tool's answer to "may a marketing call go out now?". With a known `truth.eligible`
 * the answer is right or wrong; without one (a state rule we did not re-read) it is compared with
 * `reference`, the other tool's answer, and the row says so. Called with no reference, the answer
 * is the reference itself.
 */
export function judgeTcpa(answer, truth, reference) {
  if (!answer) return { text: "not available", ok: null };
  const word = answer.eligible ? "may send" : "may not send";
  if (truth.eligible !== null) return answer.eligible === truth.eligible ? { text: word, ok: true } : { text: `${word} (wrong)`, ok: false };
  // The tool that is the reference for a row with no independent reading is right by definition.
  if (!reference) return { text: word, ok: true };
  return answer.eligible === reference.eligible ? { text: `${word} (agrees)`, ok: true } : { text: `${word} (differs)`, ok: false };
}

/**
 * Counts, per competitor, the rows of one group where ours wins, ties, loses or both miss.
 * `rows` is [{ ours: {ok}, <tool>: {ok} }]; a null ok means that side could not be judged and the row is not counted.
 */
export function tally(rows, tool) {
  const out = { wins: 0, ties: 0, losses: 0, bothMiss: 0 };
  for (const row of rows) {
    const ours = row.ours?.ok;
    const theirs = row[tool]?.ok;
    if (ours == null || theirs == null) continue;
    if (ours && theirs) out.ties += 1;
    else if (ours) out.wins += 1;
    else if (theirs) out.losses += 1;
    else out.bothMiss += 1;
  }
  return out;
}

const cell = (c) => (c ? c.text : "not available");
const table = (head, rows) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

/**
 * The whole document. `data` carries: runDate, ours { version }, tools [{ name, title, version, sha, licence, copyright, repo, kind }],
 * groups [{ id, heading, intro, truthColumn, tools: [name], rows: [{ name, truth, ours, <tool>... }] }], notRun [{ what, why }].
 */
export function render(data) {
  const names = ["ours", ...data.tools.map((t) => t.name)];
  const title = (name) => (name === "ours" ? "proactive-gate" : data.tools.find((t) => t.name === name).title);
  const out = [];
  out.push("# Comparison with other tools", "");
  out.push(`Run date: ${data.runDate} (UTC). Generated by \`npm run compare\`; do not edit by hand.`, "");
  out.push(
    "Each row below runs the same input through proactive-gate and through the other tool's own code, and prints what each answered. A row that proactive-gate loses stays in the table. The README makes claims only about rows it wins or ties.",
    "",
  );
  out.push("## Pinned versions", "");
  out.push(
    table(
      ["tool", "version", "commit", "licence", "what it is"],
      [
        ["proactive-gate", data.ours.version, "this repository", "MIT", "embedded decision library (TypeScript, Python, Go)"],
        ...data.tools.map((t) => [`[${t.title}](${t.repo.replace(/\.git$/, "")})`, t.version, `\`${t.sha.slice(0, 12)}\``, `${t.licence} (${t.copyright})`, t.kind]),
      ],
    ),
    "",
  );
  for (const g of data.groups) {
    out.push(`## ${g.heading}`, "", g.intro, "");
    out.push(table(["case", g.truthColumn, ...["ours", ...g.tools].map(title)], g.rows.map((r) => [r.name, r.truth, ...["ours", ...g.tools].map((n) => cell(r[n]))])), "");
    for (const t of g.tools) {
      const c = tally(g.rows, t);
      out.push(`Against ${title(t)}: proactive-gate wins ${c.wins}, ties ${c.ties}, loses ${c.losses}${c.bothMiss ? `, both wrong ${c.bothMiss}` : ""}.`);
    }
    out.push("");
  }
  out.push("## Summary", "");
  const summaryRows = [];
  for (const g of data.groups) for (const t of g.tools) {
    const c = tally(g.rows, t);
    summaryRows.push([g.heading, title(t), String(c.wins), String(c.ties), String(c.losses), String(c.bothMiss)]);
  }
  out.push(table(["comparison", "against", "ours wins", "ties", "ours loses", "both wrong"], summaryRows), "");
  out.push("## Not run", "");
  for (const n of data.notRun) out.push(`- **${n.what}.** ${n.why}`);
  out.push("");
  out.push("## Limits of this comparison", "");
  for (const l of data.limits) out.push(`- ${l}`);
  out.push("");
  return `${out.join("\n")}`;
}
